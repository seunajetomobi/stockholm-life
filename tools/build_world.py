#!/usr/bin/env python3
"""Build src/data/world.js (the countries and home towns of the new-life form) from two GeoNames files.

GeoNames (https://www.geonames.org) is licensed CC BY 4.0. Download, then run:
  curl -O https://download.geonames.org/export/dump/countryInfo.txt
  curl -O https://download.geonames.org/export/dump/cities15000.zip && unzip cities15000.zip
  python3 -I tools/build_world.py countryInfo.txt cities15000.txt YYYY-MM-DD > src/data/world.js

Countries: the 193 UN member states, the two UN observer states (Vatican City, Palestine), Kosovo and Taiwan (GeoNames' own codes).
Home towns: the ten largest places of each country with at least 15 000 people, and the capital first. A country with none
(for example Vatican City) gets its capital only.
"""
import re
import sys

UN = ("AF AL DZ AD AO AG AR AM AU AT AZ BS BH BD BB BY BE BZ BJ BT BO BA BW BR BN BG BF BI CV KH CM CA CF TD CL CN CO KM CG CD CR CI "
      "HR CU CY CZ DK DJ DM DO EC EG SV GQ ER EE SZ ET FJ FI FR GA GM GE DE GH GR GD GT GN GW GY HT HN HU IS IN ID IR IQ IE IL IT JM "
      "JP JO KZ KE KI KP KR KW KG LA LV LB LS LR LY LI LT LU MG MW MY MV ML MT MH MR MU MX FM MD MC MN ME MA MZ MM NA NR NP NL NZ NI "
      "NE NG MK NO OM PK PW PA PG PY PE PH PL PT QA RO RU RW KN LC VC WS SM ST SA SN RS SC SL SG SK SI SB SO ZA SS ES LK SD SR SE CH "
      "SY TJ TZ TH TL TG TO TT TN TR TM TV UG UA AE GB US UY UZ VU VE VN YE ZM ZW").split()
EXTRA = ["VA", "PS", "XK", "TW"]
NORDIC = {"DK", "FI", "IS", "NO"}
EU = set("AT BE BG HR CY CZ EE FR DE GR HU IE IT LV LT LU MT NL PL PT RO SK SI ES".split()) | {"LI", "CH"}
SCHENGEN = set("AT BE BG HR CZ DK EE FI FR DE GR HU IS IT LV LI LT LU MT NL NO PL PT RO SK SI ES SE CH".split())


def js(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def latin(s):
    return all(ord(c) < 0x250 for c in s)


def main():
    info, cities, date = sys.argv[1], sys.argv[2], sys.argv[3]
    assert re.fullmatch(r"\d{4}-\d{2}-\d{2}", date)
    codes = UN + EXTRA
    assert len(codes) == 197 and len(set(codes)) == 197, len(codes)
    ci = {}
    for line in open(info, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        f = line.rstrip("\n").split("\t")
        ci[f[0]] = (f[4], f[5])  # name, capital
    missing = [c for c in codes if c not in ci]
    assert not missing, missing
    by = {}
    for line in open(cities, encoding="utf-8"):
        f = line.split("\t")
        name, asc, cc, pop = f[1], f[2], f[8], int(f[14] or 0)
        by.setdefault(cc, []).append((pop, name if latin(name) else asc))
    out = ["/* Stockholmsliv: the countries and home towns of the new-life form (src/data/world.js).",
           "   GENERATED by tools/build_world.py from GeoNames (https://www.geonames.org), licensed CC BY 4.0, downloaded " + date + ". Do not edit by hand.",
           "   countries: [ISO 3166-1 alpha-2 code, English name, capital, group, 1 if in the Schengen area]. Group: se, nordic, eu (EU and EEA states and Switzerland) or noneu.",
           "   towns: the ten largest places (at least 15 000 people) of each country, the capital first. A classic script; Node can require() it. */",
           "(function(root){", "'use strict';", "const countries=["]
    towns = []
    for c in codes:
        name, cap = ci[c]
        g = "se" if c == "SE" else "nordic" if c in NORDIC else "eu" if c in EU else "noneu"
        out.append("  [%s,%s,%s,%s,%d]," % (js(c), js(name), js(cap), js(g), 1 if c in SCHENGEN else 0))
        lst = []
        if cap:
            lst.append(cap)
        for pop, n in sorted(by.get(c, []), reverse=True):
            if n not in lst and len(lst) < 10:
                lst.append(n)
        towns.append("  %s:[%s]," % (c, ",".join(js(x) for x in lst)))
    out.append("];")
    out.append("const towns={")
    out += towns
    out.append("};")
    out.append("const world={source:'GeoNames (https://www.geonames.org), CC BY 4.0, downloaded " + date + "',countries,towns};")
    out.append("if(typeof module==='object'&&module&&module.exports)module.exports=world;")
    out.append("else (root.StockholmLife=root.StockholmLife||{}).world=world;")
    out.append("})(globalThis);")
    print("\n".join(out))


main()
